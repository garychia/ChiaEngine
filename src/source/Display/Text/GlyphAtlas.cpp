GlyphAtlas::GlyphAtlas() : atlasWidth(0), atlasHeight(0), rgba()
{
    Rasterize();
}

GlyphAtlas::GlyphAtlas(const GlyphAtlas &other)
    : atlasWidth(other.atlasWidth), atlasHeight(other.atlasHeight), rgba(other.rgba)
{
}

GlyphAtlas &GlyphAtlas::operator=(const GlyphAtlas &other)
{
    if (this == &other)
        return *this;
    atlasWidth = other.atlasWidth;
    atlasHeight = other.atlasHeight;
    rgba = other.rgba;
    return *this;
}

uint32_t GlyphAtlas::GlyphIndex(char16_t ch) const
{
    // 只支援基本 ASCII 可列印集;其餘一律 fallback 到空白(空格 index 0)。
    if (ch < 0x20 || ch > 0x7E)
        return 0;
    return static_cast<uint32_t>(ch - 0x20);
}

void GlyphAtlas::Rasterize()
{
    atlasWidth = AtlasColumns * CellPitch - 1; // 16*9 - 1 = 143
    atlasHeight = AtlasRows * CellPitch - 1;   // 8*9 - 1 = 71
    rgba.Resize(static_cast<size_t>(atlasWidth) * atlasHeight * 4);
    for (size_t i = 0; i < rgba.GetNElements(); i++)
        rgba[i] = 0;

    const uint32_t glyphCount = AtlasColumns * AtlasRows; // 128 格(填到 0x7F,多一格備用)
    for (uint32_t g = 0; g < glyphCount; g++)
    {
        const uint32_t col = g % AtlasColumns;
        const uint32_t row = g / AtlasColumns;
        const uint32_t cellX = col * CellPitch;
        const uint32_t cellY = row * CellPitch;
        // 只有 0x20..0x7E 有實際字形;其餘格留白。
        if (g > 0x5E)
            continue; // g 對應 ch = g + 0x20,> 0x7E 的格留空
        for (uint32_t y = 0; y < CellSize; y++)
        {
            const uint8_t rowBits = kFont8x8[g][y];
            for (uint32_t x = 0; x < CellSize; x++)
            {
                if ((rowBits >> (7 - x)) & 1u)
                {
                    const size_t idx = (static_cast<size_t>(cellY + y) * atlasWidth + (cellX + x)) * 4;
                    rgba[idx + 0] = 0xFF; // R
                    rgba[idx + 1] = 0xFF; // G
                    rgba[idx + 2] = 0xFF; // B
                    rgba[idx + 3] = 0xFF; // A
                }
            }
        }
    }
}

const GlyphAtlas &GlyphAtlas::GetDefault()
{
    static const GlyphAtlas defaultAtlas;
    return defaultAtlas;
}

uint64_t GlyphAtlas::DefaultFontId()
{
    const GlyphAtlas &atlas = GetDefault();
    return FNV1A64(FNV1A64_OFFSET, atlas.GetRGBA(),
                   static_cast<size_t>(atlas.GetAtlasWidth()) * atlas.GetAtlasHeight() * 4);
}

uint32_t GlyphAtlas::GetAtlasWidth() const
{
    return atlasWidth;
}

uint32_t GlyphAtlas::GetAtlasHeight() const
{
    return atlasHeight;
}

const unsigned char *GlyphAtlas::GetRGBA() const
{
    return rgba.IsEmpty() ? nullptr : &rgba[0];
}

GlyphMetrics GlyphAtlas::GetMetrics(char16_t ch) const
{
    const uint32_t index = GlyphIndex(ch);
    const uint32_t col = index % AtlasColumns;
    const uint32_t row = index / AtlasColumns;
    const uint32_t cellX = col * CellPitch;
    const uint32_t cellY = row * CellPitch;
    GlyphMetrics metrics;
    metrics.u0 = static_cast<float>(cellX) / static_cast<float>(atlasWidth);
    metrics.v0 = static_cast<float>(cellY) / static_cast<float>(atlasHeight);
    metrics.u1 = static_cast<float>(cellX + CellSize) / static_cast<float>(atlasWidth);
    metrics.v1 = static_cast<float>(cellY + CellSize) / static_cast<float>(atlasHeight);
    metrics.advance = static_cast<float>(CellSize); // 8 字型單位(等寬)
    return metrics;
}
